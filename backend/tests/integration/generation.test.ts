/**
 * Curriculum generation end to end (AI design §10.3) with the deterministic fake provider, on a real database:
 * consent, background job, proposal, approval into an active city, failures, ownership, restart recovery.
 */
import { execSync } from "node:child_process";
import { PrismaClient } from "@prisma/client";
import { afterAll, beforeAll, describe, expect, it } from "vitest";
import { createApp } from "../../src/app.js";
import { loadAuthConfig } from "../../src/config.js";
import { TestClock } from "../../src/lib/clock.js";
import { loadAiConfig } from "../../src/modules/ai/config.js";
import { recoverGenerations } from "../../src/modules/ai/curriculum/service.js";
import { createProviders } from "../../src/modules/ai/providers/factory.js";
import { ProviderError } from "../../src/modules/ai/providers/types.js";
import { memoryMailer } from "../../src/modules/auth/mailer.js";
import { asUser, signIn } from "../helpers/auth.js";

const base = process.env.TEST_DATABASE_URL;
const suite = base ? describe : describe.skip;
const schema = `it_gen_${Date.now()}`;
const url = base ? `${base}${base.includes("?") ? "&" : "?"}schema=${schema}` : "";

suite("curriculum generation", () => {
  let prisma: PrismaClient;
  const clock = new TestClock("2026-11-19");
  const config = loadAiConfig({ AI_ENABLED: "true", AI_EVALUATION_PROVIDER: "fake", AI_GENERATION_PROVIDER: "fake" });
  let app: ReturnType<typeof createApp>;
  const H: Record<string, string> = {};
  const B: Record<string, string> = {};
  const authConfig = loadAuthConfig({ MAIL_TRANSPORT: "file" });

  const newCity = async (headers = H) =>
    (await asUser(app, headers).post("/api/cities").send({
      name: "German City", goal: "Hold everyday conversations in German",
      requirements: { currentLevel: "BEGINNER", targetLevel: "WORKING", subjects: ["Grammar", "Vocabulary", "Speaking"] },
      constraints: { hoursPerDay: 1.5, daysPerWeek: 5, startDate: "2026-11-23", timezone: "Europe/Berlin" },
    }).expect(201)).body.id as string;
  async function finished(cityId: string, version: number, headers = H) {
    for (let i = 0; i < 100; i++) {
      const v = (await asUser(app, headers).get(`/api/cities/${cityId}/curriculum/versions/${version}`).expect(200)).body;
      if (v.status !== "GENERATING") return v;
      await new Promise((r) => setTimeout(r, 50));
    }
    throw new Error("generation did not finish");
  }

  beforeAll(async () => {
    process.env.NODE_ENV = "test";
    execSync("npx prisma migrate deploy", { env: { ...process.env, DATABASE_URL: url }, stdio: "pipe" });
    prisma = new PrismaClient({ datasourceUrl: url });
    app = createApp({ prisma, clock, authConfig, mailer: memoryMailer(), ai: { config, providers: createProviders(config) } });
    Object.assign(H, (await signIn(prisma, { email: "gen@example.test", cityId: "none" })).headers);
    Object.assign(B, (await signIn(prisma, { email: "other@example.test", cityId: "none" })).headers);
  }, 120_000);
  afterAll(async () => {
    if (!prisma) return;
    await prisma.$executeRawUnsafe(`DROP SCHEMA IF EXISTS "${schema}" CASCADE`);
    await prisma.$disconnect();
  });

  it("asks for consent to send the answers before generating", async () => {
    const id = await newCity();
    const a = (await asUser(app, H).get("/api/curriculum/generation").expect(200)).body;
    expect(a).toMatchObject({ available: false, reason: "CONSENT_REQUIRED", consented: false, provider: "fake" });
    expect((await asUser(app, H).post(`/api/cities/${id}/curriculum/generate`).send({}).expect(403)).body.error.code).toBe("AI_CONSENT_REQUIRED");
    await asUser(app, H).post("/api/account/consents").send({ purpose: "AI_CURRICULUM", granted: true }).expect(200);
    expect((await asUser(app, H).get("/api/curriculum/generation").expect(200)).body).toMatchObject({ available: true, reason: null });
  });

  it("generates in the background, proposes, and builds an active city with a plan on approval", async () => {
    const id = await newCity();
    const start = await asUser(app, H).post(`/api/cities/${id}/curriculum/generate`).send({}).expect(202);
    expect(start.body).toEqual({ version: 1, status: "GENERATING" });
    const v = await finished(id, 1);
    expect(v).toMatchObject({ status: "PROPOSED", source: "GENERATED", error: null, summary: { districts: 3, start: "2026-11-23" } });
    expect(v.content.districts.map((d: { name: string }) => d.name)).toEqual(["Grammar", "Vocabulary", "Speaking"]);
    expect(v.note).toMatch(/^Generated by fake:fake-1/);
    expect(await prisma.task.count({ where: { cityId: id } })).toBe(0); // nothing in the city before approval
    expect((await asUser(app, H).post(`/api/cities/${id}/curriculum/versions/1/approve`).send({}).expect(200)).body.status).toBe("ACTIVE");
    const cur = (await asUser(app, { ...H, "X-City-Id": id }).get("/api/curriculum").expect(200)).body;
    expect(cur.districts).toHaveLength(3);
    expect(await prisma.task.count({ where: { cityId: id, source: "PLAN" } })).toBeGreaterThan(0);
    expect(await prisma.aiUsage.count({ where: { operation: "GENERATE", outcome: "OK" } })).toBe(4); // outline + 3 districts
    expect((await asUser(app, H).post(`/api/cities/${id}/curriculum/generate`).send({}).expect(409)).body.error.code).toBe("CITY_NOT_DRAFT");
  });

  it("reports a failure clearly and leaves the city untouched", async () => {
    const down = createApp({
      prisma, clock, authConfig, mailer: memoryMailer(),
      ai: { config, providers: { ...createProviders(config), generation: { name: "fake", generate: async () => { throw Object.assign(new ProviderError("PROVIDER_ERROR", "503"), { status: 503 }); } } } },
    });
    const id = await newCity();
    await asUser(down, H).post(`/api/cities/${id}/curriculum/generate`).send({}).expect(202);
    const v = await finished(id, 1);
    expect(v).toMatchObject({ status: "FAILED", summary: null, error: "The AI provider is overloaded right now. Try again in a few minutes." });
    expect((await asUser(app, H).get(`/api/cities/${id}`).expect(200)).body.status).toBe("DRAFT");
    // It can simply be started again.
    await asUser(app, H).post(`/api/cities/${id}/curriculum/generate`).send({}).expect(202);
    expect((await finished(id, 2)).status).toBe("PROPOSED");
  });

  it("never generates for another user's city, nor when AI is off", async () => {
    const id = await newCity();
    await asUser(app, B).post("/api/account/consents").send({ purpose: "AI_CURRICULUM", granted: true }).expect(200);
    expect((await asUser(app, B).post(`/api/cities/${id}/curriculum/generate`).send({}).expect(404)).body.error.code).toBe("CITY_NOT_FOUND");
    const off = createApp({ prisma, clock, authConfig, mailer: memoryMailer() });
    expect((await asUser(off, H).post(`/api/cities/${id}/curriculum/generate`).send({}).expect(403)).body.error.code).toBe("AI_DISABLED");
  });

  it("marks a generation interrupted by a restart as failed", async () => {
    const id = await newCity();
    await prisma.curriculumVersion.create({ data: { cityId: id, version: 1, status: "GENERATING", source: "GENERATED", contractVersion: 1, content: {} } });
    expect(await recoverGenerations(prisma)).toBe(1);
    expect((await finished(id, 1)).error).toMatch(/restart/);
  });
});
